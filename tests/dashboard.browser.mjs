import assert from 'node:assert/strict'
import {mkdir} from 'node:fs/promises'
import {createRequire} from 'node:module'
const require=createRequire(import.meta.url)
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const output=process.env.DASHBOARD_SCREENSHOTS || '/tmp/farmacorp-dashboard-review'
await mkdir(output,{recursive:true})
const browser=await chromium.launch({channel:'chrome',headless:true})
const errors=[]
const context=await browser.newContext({timezoneId:'America/La_Paz',reducedMotion:'reduce'})
const page=await context.newPage()
page.on('pageerror',error=>errors.push(error.message))
const funnel=()=>page.getByRole('button',{name:'Filtros globales y contexto',exact:true})
const branch=()=>page.locator('.inv-branch-button')
const dialog=()=>page.getByRole('dialog')
const base=process.env.DASHBOARD_URL || 'http://127.0.0.1:5173'
const noOverflow=async()=>assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'page horizontal overflow')
const shot=async(name)=>{await noOverflow();await page.screenshot({path:`${output}/${name}.png`,fullPage:true})}
try {
 await page.goto(base)
 await page.getByRole('heading',{name:'Dashboard de inventario',exact:true}).waitFor()
 for(const width of [360,768,1280,1920]){
  await page.setViewportSize({width,height:width===360?800:width===768?1024:1200})
  await page.evaluate(()=>scrollTo(0,0))
  await shot(`${width}-principal`)
  const before=await page.locator('.inv-kpis').evaluate(e=>e.getBoundingClientRect().top+scrollY)
  await funnel().click()
  assert.equal(await page.getByLabel('Fecha desde',{exact:true}).evaluate(e=>e===document.activeElement),true)
  const after=await page.locator('.inv-kpis').evaluate(e=>e.getBoundingClientRect().top+scrollY)
  assert.equal(after,before,'filter opening shifts cards')
  await shot(`${width}-filtros`)
  await page.keyboard.press('Escape')
  assert.equal(await funnel().evaluate(e=>e===document.activeElement),true)
  await branch().click()
  await shot(`${width}-sucursal`)
  await page.keyboard.press('Escape')
  assert.equal(await branch().evaluate(e=>e===document.activeElement),true)
  await page.getByRole('button',{name:/Lotes próximos a vencer.*90 días/}).click()
  await dialog().waitFor({state:'visible'})
  await shot(`${width}-vencimientos`)
  for(let n=0;n<8;n++){await page.keyboard.press('Tab');assert.equal(await page.evaluate(()=>document.querySelector('dialog').contains(document.activeElement)),true)}
  await page.keyboard.press('Escape')
  assert.equal(await dialog().isVisible(),false)
 }
 await page.setViewportSize({width:1280,height:1000})
 await funnel().click()
 await page.getByLabel('Fecha desde',{exact:true}).fill('2026-10-28')
 await page.getByLabel('Fecha hasta',{exact:true}).fill('2026-10-27')
 await page.getByRole('button',{name:'Aplicar filtros',exact:true}).click()
 assert.match(await page.getByRole('alert').innerText(),/posterior/)
 await shot('1280-validacion')
 await page.getByLabel('Fecha desde',{exact:true}).fill('2026-10-01')
 await page.getByLabel('Región',{exact:true}).selectOption('Altiplano')
 assert.deepEqual(await page.getByLabel('Departamento',{exact:true}).locator('option').allTextContents(),['Todos los departamentos','La Paz'])
 await page.getByLabel('Departamento',{exact:true}).selectOption('La Paz')
 await page.getByRole('button',{name:'Aplicar filtros',exact:true}).click()
 assert.match(await page.getByRole('alert').innerText(),/sucursal.*contexto/)
 await branch().click()
 assert.equal(await page.locator('.inv-branch-menu button').count(),1)
 await page.locator('.inv-branch-menu button').click()
 await page.getByRole('button',{name:'Aplicar filtros',exact:true}).click()
 assert.match(await page.locator('.inv-summary').innerText(),/Altiplano.*La Paz/)
 assert.match(await branch().innerText(),/CEDIS/)
 await shot('1280-aplicados')
 await page.getByRole('button',{name:/Lotes próximos a vencer.*90 días/}).click()
 assert.match(await dialog().innerText(),/No hay lotes próximos a vencer/)
 await page.keyboard.press('Escape')
 await funnel().click()
 await page.getByRole('button',{name:'Limpiar filtros',exact:true}).click()
 assert.match(await page.locator('.inv-summary').innerText(),/Todas las regiones.*Todos los departamentos/)
 await funnel().click()
 await page.getByRole('heading',{name:'Dashboard de inventario',exact:true}).click()
 assert.equal(await page.locator('.inv-filter-panel').count(),0)
 await branch().click()
 await page.locator('.inv-branch-menu button').filter({hasText:'Equipetrol'}).click()
 await page.getByRole('button',{name:/Lotes próximos a vencer.*90 días/}).click()
 await dialog().getByRole('button',{name:'Paracetamol 500 mg',exact:true}).click()
 assert.equal(await page.locator('.filters input').first().inputValue(),'L-1001')
 await page.getByRole('button',{name:'Resumen',exact:true}).click()
 const persisted=await page.evaluate(()=>localStorage.getItem('farmacorp-demo'))
 await page.locator('.inv-chart-row').first().click()
 await page.getByRole('heading',{name:'Existencias',exact:true}).waitFor()
 assert.equal(await page.locator('.filters select').first().inputValue(),'Sucursal Equipetrol')
 await page.getByRole('button',{name:'Resumen',exact:true}).click()
 await page.locator('.inv-count-card').first().click()
 await page.getByRole('heading',{name:'Control de inventario',exact:true}).waitFor()
 await page.getByRole('button',{name:'Resumen',exact:true}).click()
 await page.locator('.inv-action').filter({hasText:'Reordenar'}).click()
 await page.getByRole('heading',{name:'Reposición',exact:true}).waitFor()
 await page.getByRole('button',{name:/Inventario/}).first().click()
 await page.getByRole('heading',{name:'Dashboard de inventario',exact:true}).waitFor()
 assert.equal(await page.evaluate(()=>localStorage.getItem('farmacorp-demo')),persisted,'navigation must not approve or mutate data')
 // Exercise explicit count registration and approval in this isolated browser context.
 await page.locator('.inv-count-card').first().click()
 await page.locator('select[name="location"]').selectOption('Sucursal Equipetrol')
 const physical=await page.evaluate(()=>JSON.parse(localStorage.getItem('farmacorp-demo')).lots.filter(l=>l.productId==='P01'&&l.location==='Sucursal Equipetrol').reduce((n,l)=>n+l.quantity,0))
 await page.locator('input[name="physical"]').fill(String(physical))
 await page.locator('input[name="reason"]').fill('Prueba aislada: conteo sin diferencias')
 await page.getByRole('button',{name:'Registrar conteo pendiente',exact:true}).click()
 await page.getByRole('button',{name:'Aprobar ajuste',exact:true}).click()
 assert.match(await page.getByRole('status').innerText(),/Solo Inventario o Administrador/)
 await page.getByLabel('Perfil activo',{exact:true}).selectOption('Inventario')
 await page.getByRole('button',{name:'Aprobar ajuste',exact:true}).click()
 assert.ok(await page.evaluate(()=>JSON.parse(localStorage.getItem('farmacorp-demo')).counts[0].approvedAt))
 await page.getByRole('button',{name:'Resumen',exact:true}).click()
 assert.match(await page.locator('.inv-count-card').first().innerText(),/100 %.*1 de 1/s)
 await shot('1280-conteo-fechado')
 await page.getByRole('button',{name:'Recepciones',exact:true}).click()
 await page.getByLabel('Perfil activo',{exact:true}).selectOption('Encargado')
 await page.getByRole('button',{name:/Ventas/}).first().click()
 await page.locator('input[name="saleId"]').fill('DASHBOARD-BROWSER-SALE')
 await page.locator('select[name="location"]').selectOption('Sucursal Equipetrol')
 await page.locator('input[name="amount"]').fill('20')
 await page.getByRole('button',{name:'Registrar venta',exact:true}).click()
 assert.match(await page.getByRole('status').innerText(),/Venta confirmada.*FEFO/)
 await page.getByRole('button',{name:/Inventario/}).first().click()
 assert.equal(await page.locator('.inv-kpi-value').nth(1).innerText(),'1')
 assert.equal(await page.locator('.inv-kpi-value').nth(2).innerText(),'1')
 assert.match(await page.locator('.inv-chart-row').filter({hasText:'Paracetamol 500 mg'}).innerText(),/28 \/ ROP 25/)
 await shot('1280-consumo-y-stock')
 await funnel().click()
 await page.getByLabel('Fecha desde',{exact:true}).fill('2020-01-01')
 await page.getByLabel('Fecha hasta',{exact:true}).fill('2020-01-01')
 await page.getByRole('button',{name:'Aplicar filtros',exact:true}).click()
 assert.match(await page.locator('.inv-count-card').first().innerText(),/Sin conteos/)
 assert.equal(await page.locator('main').count(),1)
 assert.deepEqual(errors,[])
 console.log(`PASS: 4 widths × 4 states; validation, geography, atomic application, clear, outside click, keyboard/focus, dialog trap, module links, no mutation, dated/empty counts, reduced motion. Captures: ${output}`)
} finally {await browser.close()}
